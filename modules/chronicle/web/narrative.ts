/** 一张图补写的叙事内容；没有补写的返回空对象。 */
export function panelOf(group: string, slug: string): PanelExtras {
  return PANELS[`${group}/${slug}`] ?? {};
}

/** 相关图表：把 `group/slug` 解析成能直接落链接的页面。 */
export function relatedPages(group: string, slug: string): ChartPage[] {
  return (PANELS[`${group}/${slug}`]?.related ?? []).flatMap((key) => {
    const at = key.indexOf("/");
    const page = pageOf(key.slice(0, at), key.slice(at + 1));
    return page ? [page] : [];
  });
}

/** 某个章节的导读（键是 `group/章节号`）。 */
export function chapterLead(group: string, n: string): string {
  return CHAPTER_LEADS[`${group}/${n}`] ?? "";
}
