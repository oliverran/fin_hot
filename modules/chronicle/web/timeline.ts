/** 一条大事记里的代表个股。 */
export interface TimelineStock {
  name: string;
  /** 证券代码；有它就挂到「上市公司背景卡」查询，退市个股不填。 */
  code?: string;
  /** 一句它为什么成为这个时点的代表。 */
  note: string;
}

/** 大事记里的一条事件。 */
export interface TimelineEvent {
  /** 显示用的时间，精确到月即可（如 "2005-04"）。 */
  date: string;
  title: string;
  /** 一段叙述，讲清这件事改变了什么。 */
  summary: string;
  /** 这个时点上的代表个股；只在个股本身就是故事时才挂。 */
  stocks?: TimelineStock[];
}

/** 一个时代：一段断代史，下挂若干事件。 */
export interface TimelineEra {
  key: string;
  /** 年代区间与时代的名字，如 "1990–1995 · 草莽初创"。 */
  label: string;
  /** 一句话概要。 */
  intro: string;
  /** 这个时代的代表个股。 */
  stocks?: TimelineStock[];
  events: TimelineEvent[];
}

