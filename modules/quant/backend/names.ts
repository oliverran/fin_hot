/** 从任意写法里取出 6 位代码：600519、600519.SS、SS600519 都认。 */
const codeOf = (symbol: string) => symbol.match(/\d{6}/)?.[0] ?? null;

/**
 * 把产物里的代码补成「代码 + 名称 + 行业」。代码统一成 6 位（600519.SS → 600519）；
 * 表里没有的就不猜行业，名称退回代码本身、行业留空（页面显示「—」）。
 */
export function stockInfo(symbol: string): { ticker: string; name: string; sector: string } {
  const code = codeOf(symbol) ?? symbol;
  const found = STOCKS[code];
  return found ? { ticker: code, name: found[0], sector: found[1] } : { ticker: code, name: code, sector: "—" };
}
